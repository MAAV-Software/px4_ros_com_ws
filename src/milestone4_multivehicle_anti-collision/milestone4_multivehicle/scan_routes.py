"""Milestone 4's scan of the competition field: four lawnmower routes, written as waypoint YAMLs.

The field is 80 by 300 ft (24.384 by 91.44 m), north-south. World X=East, Y=North, metres,
with the field's south-west corner at (0, 0). The camera sees 2 m across the direction of
travel by 3 m along it, so rows are 2 m apart and each row's ends sit 1.5 m inside the field.

- Drones 0-2 each take a third of the width and fly north-south rows over the whole length,
  starting at the south end, then return to their spawn and land.
- Drone 3 flies east-west rows over the whole field, starting at the south edge and working
  north, crossing the other three's strips the whole time. It lands where it finishes.

Every drone spawns 3 m south of the field (the web launcher's "south edge" SITL layout).
Regenerate the YAMLs with:
  python3 -m milestone4_multivehicle.scan_routes resource/
"""
import math
import os
import sys

FT_M = 0.3048
FIELD_EAST_M = 80 * FT_M
FIELD_NORTH_M = 300 * FT_M
ACROSS_M = 2.0           # camera footprint across the direction of travel: row spacing
ALONG_M = 3.0            # camera footprint along the direction of travel
ALTITUDE_M = 5.0
TAKEOFF_HOLD_S = 10.0    # all four reach altitude before anyone sets off
FINAL_HOLD_S = 2.0
# World (east, north) spawn points; must match the web launcher's "south" layout and
# scan_launch.py's spawn defaults.
SPAWNS = ((1.0, -3.0), (9.0, -3.0), (17.0, -3.0), (23.0, -3.0))
STRIP_DRONES = 3


def lanes(extent, spacing=ACROSS_M):
    """Row centres spacing apart, the first spacing/2 in; one more at the far edge if a sliver
    is left, so the whole extent is covered with the least overlap."""
    centres = []
    centre = spacing / 2
    while centre + spacing / 2 <= extent + 1e-9:
        centres.append(round(centre, 3))
        centre += spacing
    if centres[-1] + spacing / 2 < extent - 1e-9:
        centres.append(round(extent - spacing / 2, 3))
    return centres


def strip_rows(drone):
    """North-south row eastings for drone 0, 1 or 2: the lanes whose centre is in its third."""
    third = FIELD_EAST_M / STRIP_DRONES
    return [e for e in lanes(FIELD_EAST_M) if drone * third <= e < (drone + 1) * third
            or (drone == STRIP_DRONES - 1 and e >= FIELD_EAST_M - 1e-9)]


def world_route(drone):
    """[(east, north)] row ends in flying order, after takeoff and before return or landing."""
    points = []
    if drone < STRIP_DRONES:
        south, north = ALONG_M / 2, round(FIELD_NORTH_M - ALONG_M / 2, 3)
        for i, east in enumerate(strip_rows(drone)):
            ends = [(east, south), (east, north)]
            points += ends if i % 2 == 0 else ends[::-1]
    else:
        west, east = ALONG_M / 2, round(FIELD_EAST_M - ALONG_M / 2, 3)
        for i, north in enumerate(lanes(FIELD_NORTH_M)):
            ends = [(east, north), (west, north)]  # starts from the east, nearest its spawn
            points += ends if i % 2 == 0 else ends[::-1]
    return points


def heading(frm, to):
    """PX4 yaw (0 north, pi/2 east) from one world (east, north) point to another."""
    return math.atan2(to[0] - frm[0], to[1] - frm[1])


def waypoints(drone):
    spawn = SPAWNS[drone]
    route = world_route(drone)
    if drone < STRIP_DRONES:
        route = route + [spawn]  # return home and land off the field

    def local(point):
        return [round(point[1] - spawn[1], 3), round(point[0] - spawn[0], 3), -ALTITUDE_M]

    out = [{'pos': local(spawn), 'yaw': round(heading(route[0], route[1]), 4), 'hold_s': TAKEOFF_HOLD_S}]
    previous = spawn
    for i, point in enumerate(route):
        # Face along the row: rows are flown start to end, so yaw is set by the leg that
        # follows a row's start and the leg into a row's end.
        if i + 1 < len(route) and i % 2 == 0:
            yaw = heading(point, route[i + 1])
        else:
            yaw = heading(previous, point)
        hold = FINAL_HOLD_S if i == len(route) - 1 else 0.0
        out.append({'pos': local(point), 'yaw': round(yaw, 4), 'hold_s': hold})
        previous = point
    return out


def yaml_text(drone):
    rows = strip_rows(drone) if drone < STRIP_DRONES else lanes(FIELD_NORTH_M)
    kind = ('north-south rows at east ' + ', '.join(f'{e:g}' for e in rows) + ' m'
            if drone < STRIP_DRONES else f'{len(rows)} east-west rows, north {rows[0]:g} to {rows[-1]:g} m')
    lines = [
        f'# Milestone 4 field scan, drone {drone} (system_id {drone + 1}). Generated by',
        '# milestone4_multivehicle/scan_routes.py; edit that and regenerate, not this file.',
        f'# Spawn: world east {SPAWNS[drone][0]:g}, north {SPAWNS[drone][1]:g} m; field SW corner at (0, 0).',
        f'# {kind}, {ACROSS_M:g} m apart, at {ALTITUDE_M:g} m.',
        '# Local North/East/Down from the spawn, yaw radians.',
        'waypoints:',
    ]
    for w in waypoints(drone):
        lines.append(f"  - {{pos: [{', '.join(f'{v:g}' for v in w['pos'])}], "
                     f"yaw: {w['yaw']:g}, hold_s: {w['hold_s']:g}}}")
    return '\n'.join(lines) + '\n'


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    folder = argv[0] if argv else 'resource'
    for drone in range(len(SPAWNS)):
        path = os.path.join(folder, f'milestone4_scan_{drone}.yaml')
        with open(path, 'w') as stream:
            stream.write(yaml_text(drone))
        print(f'wrote {path} ({len(waypoints(drone))} waypoints)')


if __name__ == '__main__':
    main()
