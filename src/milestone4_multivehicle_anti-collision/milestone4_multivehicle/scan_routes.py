"""Milestone 4's scan of the competition field: three lawnmower routes and a checker's
takeoff, written as waypoint YAMLs.

The field is 80 by 300 ft (24.384 by 91.44 m), north-south. World X=East, Y=North, metres,
with the field's south-west corner at (0, 0).

The camera sees 3 m along the drone's nose by 2 m across it from 5 m up, and the footprint
is assumed to grow in proportion to height. Every drone holds its nose east for the whole
flight and flies its rows sideways, so the footprint's long side lies across the row. From
5.6 m that side is 3.36 m, and 9 north-south rows 2.63 m apart cover the 24.384 m width.

Drones 0-2 mow: each takes three neighbouring rows, north up the first, south down the
second, north up the third, and lands 3 m north of the field. They fly the same pattern
7.9 m apart. Drone 3 is the checker: its route is only a takeoff over its spawn, and the
mine survey (mines.py) then sends it along the best path found so far.

Every drone spawns 3 m south of the field (the web launcher's "south edge" SITL layout).
Regenerate the YAMLs with:
  python3 -m milestone4_multivehicle.scan_routes resource/
"""
import math
import os
import sys

FT_M = 0.3048
FIELD_EAST_M = 80 * FT_M
FIELD_NORTH_M = 300 * FT_M
CAMERA_ALTITUDE_M = 5.0  # the height the camera footprint below was given for
CAMERA_NOSE_M = 3.0      # footprint along the drone's nose from that height
CAMERA_SIDE_M = 2.0      # footprint across the drone's nose from that height
ALTITUDE_M = 5.6
ROWS = 9
ROWS_PER_DRONE = 3
MOWERS = 3               # drones 0-2 fly the rows; the last drone checks the best path
YAW = math.pi / 2        # nose east the whole flight, so the long side lies across the rows
ACCEPTANCE_M = 0.5       # the controller's waypoint radius: it turns this far short of a row end
TAKEOFF_HOLD_S = 10.0    # all four reach altitude before anyone sets off
FINAL_HOLD_S = 2.0
# World (east, north) spawn points; must match the web launcher's "south" layout and
# scan_launch.py's spawn defaults.
SPAWNS = ((1.0, -3.0), (9.0, -3.0), (17.0, -3.0), (23.0, -3.0))
LANDING_NORTH_M = round(FIELD_NORTH_M + 3.0, 3)  # the mowers end at the north edge


def footprint():
    """(east, north) size of the camera footprint at the scan altitude, nose east."""
    scale = ALTITUDE_M / CAMERA_ALTITUDE_M
    return CAMERA_NOSE_M * scale, CAMERA_SIDE_M * scale


def row_eastings():
    """Row centres: the outer footprints end on the field's edges, the rest are evenly spaced."""
    half = footprint()[0] / 2
    step = (FIELD_EAST_M - 2 * half) / (ROWS - 1)
    return [round(half + i * step, 3) for i in range(ROWS)]


def drone_rows(drone):
    """The row eastings mower 0-2 flies, in flying order (west to east); none for the checker."""
    if drone >= MOWERS:
        return []
    return row_eastings()[drone * ROWS_PER_DRONE:(drone + 1) * ROWS_PER_DRONE]


def row_ends():
    """(south, north) row-end northings. The footprint must reach the field's edge before the
    drone turns, and it turns ACCEPTANCE_M short of the waypoint, so the ends sit that much
    further out than half a footprint inside the field."""
    inset = footprint()[1] / 2 - ACCEPTANCE_M
    return round(inset, 3), round(FIELD_NORTH_M - inset, 3)


def world_route(drone):
    """[(east, north)] in flying order after takeoff: up, down and up its rows, then on to
    land north of the field. Empty for the checker."""
    south, north = row_ends()
    points = []
    for i, east in enumerate(drone_rows(drone)):
        ends = [(east, south), (east, north)]
        points += ends if i % 2 == 0 else ends[::-1]
    return points + [(points[-1][0], LANDING_NORTH_M)] if points else []


def checker_landings():
    """World places north of the field where the checker can land: midway between the mowers'."""
    landed = [world_route(d)[-1][0] for d in range(MOWERS)]
    return [(round((a + b) / 2, 3), LANDING_NORTH_M) for a, b in zip(landed, landed[1:])]


def waypoints(drone):
    spawn = SPAWNS[drone]
    route = [spawn] + world_route(drone)
    out = []
    for i, point in enumerate(route):
        hold = TAKEOFF_HOLD_S if i == 0 else FINAL_HOLD_S if i == len(route) - 1 else 0.0
        out.append({'pos': [round(point[1] - spawn[1], 3), round(point[0] - spawn[0], 3), -ALTITUDE_M],
                    'yaw': round(YAW, 4), 'hold_s': hold})
    return out


def yaml_text(drone):
    east, north = footprint()
    lines = [
        f'# Milestone 4 field scan, drone {drone} (system_id {drone + 1}). Generated by',
        '# milestone4_multivehicle/scan_routes.py; edit that and regenerate, not this file.',
        f'# Spawn: world east {SPAWNS[drone][0]:g}, north {SPAWNS[drone][1]:g} m; field SW corner at (0, 0).',
        ('# North-south rows at east ' + ', '.join(f'{e:g}' for e in drone_rows(drone))
         + f' m, at {ALTITUDE_M:g} m, nose east ({east:g} m across the row by {north:g} m along it).')
        if drone < MOWERS else
        f'# The checker: takes off to {ALTITUDE_M:g} m and waits for the mine survey to send it along the best path.',
        '# Local North/East/Down from the spawn, yaw radians.',
        'waypoints:',
    ]
    for w in waypoints(drone):
        lines.append(f"  - {{pos: [{', '.join(f'{v:g}' for v in w['pos'])}], "
                     f"yaw: {w['yaw']:g}, hold_s: {w['hold_s']:g}}}")
    return '\n'.join(lines) + '\n'


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    folder = argv[0] if argv else 'resource'
    for drone in range(len(SPAWNS)):
        path = os.path.join(folder, f'milestone4_scan_{drone}.yaml')
        with open(path, 'w') as stream:
            stream.write(yaml_text(drone))
        print(f'wrote {path} ({len(waypoints(drone))} waypoints)')


if __name__ == '__main__':
    main()
