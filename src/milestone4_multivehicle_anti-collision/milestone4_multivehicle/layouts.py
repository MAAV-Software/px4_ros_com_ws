LAYOUTS = {name: frozenset(tuple(int(v) for v in cell.split(',')) for cell in cells.split())
           for name, cells in _CELLS.items()}
SITE_SEEDS = tuple(name for name in LAYOUTS if name != 'norway')


def layout_name(seed):
    """The stored layout a mine_seed names, or None for a whole number (a generated field).
    ROS reads 0.1934 as a number, so numbers are matched by value."""
    text = str(seed).strip().lower()
    if text in LAYOUTS:
        return text
    try:
        number = float(text)
    except ValueError:
        raise ValueError(f'mine_seed {seed!r} is neither a whole number nor one of: ' + ', '.join(LAYOUTS))
    if number == int(number):
        return None
    if f'{number:g}' in LAYOUTS:
        return f'{number:g}'
    raise ValueError(f'no stored layout for mine_seed {seed!r}; there are: ' + ', '.join(LAYOUTS))


def seed_value(seed):
    """A mine_seed as given on the command line: a stored layout's name, or a whole number."""
    return layout_name(seed) or int(float(seed))
